import { Window } from 'happy-dom';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const dir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(dir, '..');
const w = new Window({ url: 'https://example.test/', width: 390, height: 844 });
w.document.write('<!doctype html><html dir="rtl"><body><div id="amphp-storefront-root" dir="rtl"></div></body></html>');
w.matchMedia = () => ({matches:false,addListener(){},removeListener(){},addEventListener(){},removeEventListener(){}});
w.requestAnimationFrame = cb => setTimeout(cb, 0); w.scrollTo = () => {};
w.eval(fs.readFileSync(path.join(dir, 'boot-sample.js'), 'utf8'));
const sample = w.AMPHP_STOREFRONT.products[0];
w.AMPHP_STOREFRONT.settings.products_per_page = 8;
w.AMPHP_STOREFRONT.settings.enable_ai_product_images = false;
const dates = [0, 300, 100, 200, 300, 0, 400, 600, 500, 700];
w.AMPHP_STOREFRONT.products = dates.map((created_ts, i) => ({...sample, id:String(i), title:'محصول ' + i, category:i < 5 ? 'گروه الف' : 'گروه ب', created_ts}));
w.AMPHP_STOREFRONT.meta.total_count = dates.length;
w.eval(fs.readFileSync(path.join(root, 'asset/js/storefront/storefront.js'), 'utf8'));
const wait = () => new Promise(r => setTimeout(r, 150));
const titles = () => [...w.document.querySelectorAll('.sf-grid .sf-card-title')].map(n => n.textContent.trim());
const sort = async value => { const select = w.document.querySelector('.sf-toolbar .sf-select'); select.value = value; select.dispatchEvent(new w.Event('change', {bubbles:true})); await wait(); };
await wait();
const select = w.document.querySelector('.sf-toolbar .sf-select');
assert.ok([...select.options].some(o => o.textContent === 'جدیدترین'));
assert.ok([...select.options].some(o => o.textContent === 'قدیمی‌ترین'));
// Sorting from page 2 must reset the page and sort before slicing.
[...w.document.querySelectorAll('.sf-pagination .sf-page-btn')].find(x => x.textContent.includes('بعدی')).click(); await wait();
await sort('newest');
assert.deepEqual(titles(), ['محصول 9','محصول 7','محصول 8','محصول 6','محصول 1','محصول 4','محصول 3','محصول 2']);
assert.ok(w.document.querySelector('.sf-sort-hint').textContent.includes('بدون تاریخ'));
[...w.document.querySelectorAll('.sf-pagination .sf-page-btn')].find(x => x.textContent.includes('بعدی')).click(); await wait();
assert.deepEqual(titles(), ['محصول 0','محصول 5'], 'Undated products remain at end in original order');
await sort('oldest');
assert.deepEqual(titles(), ['محصول 2','محصول 3','محصول 1','محصول 4','محصول 6','محصول 8','محصول 7','محصول 9']);
[...w.document.querySelectorAll('.sf-cat-pills .sf-pill')].find(x => x.textContent.includes('گروه الف')).click(); await wait();
assert.deepEqual(titles(), ['محصول 2','محصول 3','محصول 1','محصول 4','محصول 0'], 'Sort applies after category filtering');
await sort('newest');
assert.deepEqual(titles(), ['محصول 1','محصول 4','محصول 3','محصول 2','محصول 0'], 'Equal timestamps retain source order');
console.log('Storefront date sort smoke tests passed'); w.happyDOM.abort();
