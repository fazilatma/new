import { Window } from 'happy-dom';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const dir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(dir, '..');
const w = new Window({url:'https://example.test/', width:390, height:844});
w.document.write('<!doctype html><html dir="rtl"><body><div id="amphp-storefront-root" dir="rtl"></div></body></html>');
w.matchMedia = () => ({matches:false,addListener(){},removeListener(){},addEventListener(){},removeEventListener(){}});
w.requestAnimationFrame = (cb) => setTimeout(cb, 0);
w.scrollTo = () => {};
w.eval(fs.readFileSync(path.join(dir, 'boot-sample.js'), 'utf8'));
const products = w.AMPHP_STOREFRONT.products;
products[0].category = 'مانتو پاتریس | پوشاک';
products[0].title = 'محصول مانتو پاتریس';
products[1].category = 'پوشاک';
products[2].category = 'کیف - مانتو\u200cپاتریس';
products[3].category = 'مانتو پاتریس';
w.AMPHP_STOREFRONT.settings.enable_ai_product_images = false;
w.fetch = async () => ({ json: async () => ({success:true,data:{product:{title:'محصول مانتو پاتریس',category:'مانتو پاتریس | پوشاک',description:'توضیح'}}}) });
w.eval(fs.readFileSync(path.join(root, 'asset/js/storefront/storefront.js'), 'utf8'));
const wait = () => new Promise(r => setTimeout(r, 150));
await wait();
const $ = (q) => w.document.querySelector(q);
const buttons = [...w.document.querySelectorAll('.sf-cat-pills .sf-pill')];
assert.equal(buttons.some(x => x.textContent.includes('مانتو پاتریس')), false, 'Category controls hide brand');
assert.equal(buttons.filter(x => x.textContent.includes('پوشاک')).length, 1, 'Equivalent categories grouped');
assert.ok(buttons.some(x => x.textContent.includes('کیف')), 'Remaining category retained');
assert.ok(buttons.some(x => x.textContent.includes('عمومی')), 'Empty category has fallback');
assert.ok(w.document.querySelector('.sf-card-title').textContent.includes('مانتو پاتریس'), 'Product title untouched');
assert.equal(w.document.querySelectorAll('.sf-mob-bar .sf-mob-item').length, 4);
assert.equal(w.document.querySelectorAll('.sf-mob-bar .sf-mob-icon').length, 4);
assert.ok([...w.document.querySelectorAll('.sf-mob-icon')].every(x => x.getAttribute('aria-hidden') === 'true'));
$('.sf-mob-menu').click(); await wait();
assert.ok($('.sf-menu-head'), 'Mobile menu opens');
$('.sf-menu-head .sf-close').click(); await wait();
assert.ok(!$('.sf-menu-head'), 'Mobile menu closes');
buttons.find(x => x.textContent.includes('پوشاک')).click();
await wait();
assert.equal(w.document.querySelectorAll('.sf-card').length, 2, 'Filtered normalized category includes both products');
$('.sf-card-title').click(); await wait();
assert.ok(!w.document.querySelector('.sf-pdp-cat')?.textContent.includes('مانتو پاتریس'), 'AJAX details category sanitized');
console.log('Category and mobile menu smoke tests passed');
w.happyDOM.abort();
